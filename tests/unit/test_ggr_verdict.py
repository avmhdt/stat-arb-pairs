"""AC-H-01 on the committed headline replication (owner ruling 2026-11-03).

Signs and the top-20 level pass; the ordering check is a documented miss, kept as a strict
expected failure. The table is regenerated by ``statarb evaluate replication``.
"""

from __future__ import annotations

import json
from pathlib import Path

import polars as pl
import pytest

TABLES = Path(__file__).resolve().parents[2] / "results" / "tables"
VERDICT = json.loads((TABLES / "ggr_replication.json").read_text(encoding="utf-8"))


def test_signs_and_top20_level() -> None:
    assert VERDICT["all_same_sign"] is True
    for wait in ("no_wait", "wait_one_day"):
        assert VERDICT[f"{wait}_top20_within_30pct"] is True
        assert VERDICT[f"{wait}_top20_t_gt_2"] is True


@pytest.mark.xfail(
    strict=True,
    reason=(
        "AC-H-01 ordering, owner ruling 2026-11-03: accepted as a finding. Pairs 101-120 "
        "out-earn the top 5 and top 20 in 1999-2002, with and without the one-day wait; "
        "GGR's own Table 8 (1989-2002) has the top 5 below 101-120 too."
    ),
)
@pytest.mark.parametrize("wait", ["no_wait", "wait_one_day"])
def test_paper_ordering(wait: str) -> None:
    assert VERDICT[f"{wait}_ordering_holds"] is True


def test_bounce_does_not_explain_the_ordering() -> None:
    """After waiting a day, pairs 101-120 still earn more than the top pairs."""
    bounce = pl.read_csv(TABLES / "ggr_bounce.csv")
    rows = {row["portfolio"]: row for row in bounce.iter_rows(named=True)}
    assert rows["101-120"]["spread_sigma_mean"] > rows["top20"]["spread_sigma_mean"]
    assert rows["101-120"]["fully_invested_drop_bps"] > rows["top20"]["fully_invested_drop_bps"]
    assert (
        rows["101-120"]["fully_invested_wait_one_day"]
        > rows["top20"]["fully_invested_wait_one_day"]
    )
