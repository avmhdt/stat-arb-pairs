"""Aggregate tables for the memo, read from ``results/`` only (FR-29, FR-30).

M3 builds ``results/tables/fdr_by_window.csv`` from the latest headline selection of each
cointegration config, and regenerates the table block in ``docs/multiple_testing.md``.
Everything written here is an aggregate: no security ids.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import polars as pl

from statarb.selection.runner import SELECTION_INFO
from statarb.selection.select import fdr_summary

START = "<!-- fdr-table:start -->"
END = "<!-- fdr-table:end -->"


@dataclass(frozen=True)
class Selection:
    """A selection run found under ``results/runs``."""

    path: Path
    info: dict[str, object]


def find_selections(runs: Path) -> list[Selection]:
    """Every selection run, newest last."""
    found = []
    for info_path in sorted(runs.glob(f"select-*/{SELECTION_INFO}")):
        info = json.loads(info_path.read_text(encoding="utf-8"))
        found.append(Selection(info_path.parent, info))
    return sorted(found, key=lambda item: str(item.info.get("created_at", "")))


def latest_coint(runs: Path, profile: str = "headline") -> dict[str, Selection]:
    """The newest cointegration selection per config name on ``profile``."""
    latest: dict[str, Selection] = {}
    for item in find_selections(runs):
        if item.info.get("method") == "engle_granger" and item.info.get("data_profile") == profile:
            latest[str(item.info["name"])] = item
    return latest


def fdr_by_window(runs: Path, profile: str = "headline") -> pl.DataFrame:
    """One row per (config, window): m, raw rejections, BH and BY discoveries, traded."""
    frames = []
    for name, item in sorted(latest_coint(runs, profile).items()):
        tested = pl.read_parquet(item.path / "pairs.parquet")
        frames.append(
            fdr_summary(tested).with_columns(
                pl.lit(name).alias("config"), pl.lit(profile).alias("data_profile")
            )
        )
    if not frames:
        return pl.DataFrame()
    table = pl.concat(frames)
    return table.select(
        "config", "data_profile", *[c for c in table.columns if c not in ("config", "data_profile")]
    )


def by_year(table: pl.DataFrame) -> pl.DataFrame:
    """Window means by formation-end year, for the doc."""
    return (
        table.with_columns(pl.col("window_id").str.slice(0, 4).alias("year"))
        .group_by("config", "year", maintain_order=True)
        .agg(
            pl.len().alias("windows"),
            pl.col("m").mean().round(0).alias("mean_m"),
            pl.col("raw_p_lt_05").mean().round(1).alias("mean_raw_p_lt_05"),
            pl.col("expected_false_raw").mean().round(1).alias("mean_expected_false_raw"),
            pl.col("bh_discoveries").mean().round(2).alias("mean_bh"),
            pl.col("by_discoveries").mean().round(2).alias("mean_by"),
            pl.col("traded").mean().round(2).alias("mean_traded"),
            (pl.col("bh_discoveries") < 5).sum().alias("windows_bh_lt_5"),
        )
        .sort("config", "year")
    )


def markdown(table: pl.DataFrame) -> str:
    """A plain Markdown table."""
    header = "| " + " | ".join(table.columns) + " |"
    rule = "|" + "---|" * len(table.columns)
    body = [
        "| "
        + " | ".join(f"{value:g}" if isinstance(value, float) else str(value) for value in row)
        + " |"
        for row in table.iter_rows()
    ]
    return "\n".join([header, rule, *body])


def write_fdr_outputs(
    runs: Path, tables: Path, doc: Path, profile: str = "headline"
) -> pl.DataFrame:
    """Write ``fdr_by_window.csv`` and the generated block of ``docs/multiple_testing.md``."""
    table = fdr_by_window(runs, profile)
    if table.is_empty():
        raise FileNotFoundError(f"no {profile} cointegration selection under {runs}")
    tables.mkdir(parents=True, exist_ok=True)
    table.write_csv(tables / "fdr_by_window.csv")
    yearly = by_year(table)
    text = doc.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise ValueError(f"{doc} lacks the generated-table markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    totals = table.select(
        pl.len().alias("windows"),
        pl.col("m").sum().alias("tests"),
        pl.col("raw_p_lt_05").sum().alias("raw_p_lt_05"),
        pl.col("expected_false_raw").sum().round(0).alias("expected_false_raw"),
        pl.col("bh_discoveries").sum().alias("bh"),
        pl.col("by_discoveries").sum().alias("by"),
        pl.col("traded").sum().alias("traded"),
    )
    block = "\n".join(
        [
            START,
            "",
            f"Generated by `statarb report` from the latest {profile} selection; window means "
            "by formation-end year. Full per-window rows: `results/tables/fdr_by_window.csv`.",
            "",
            markdown(totals),
            "",
            markdown(yearly),
            "",
            END,
        ]
    )
    doc.write_text(head + block + tail, encoding="utf-8", newline="\n")
    return table
